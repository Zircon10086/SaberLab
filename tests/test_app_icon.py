"""App / site icon regression tests.

The SVG master (docs/screenshots/saberlab-icon.svg) is the only hand-edited file; the
.ico and .png renders and the site copy are generated by _tools/make_icon.py. These tests
catch a stale copy, a malformed .ico (Windows then silently shows python.exe's icon), and
an SVG that stops being a self-contained image.
"""
from __future__ import annotations

import re
import struct
import sys
import unittest
import xml.etree.ElementTree as ET
import zlib
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

MASTER = PROJECT_ROOT / "docs" / "screenshots" / "saberlab-icon.svg"
SITE_SVG = PROJECT_ROOT / "site" / "assets" / "favicon.svg"
ICO = PROJECT_ROOT / "frontend" / "saberlab.ico"
SITE_PNG32 = PROJECT_ROOT / "site" / "assets" / "favicon-32.png"
SITE_TOUCH = PROJECT_ROOT / "site" / "assets" / "apple-touch-icon.png"
ICO_SIZES = [16, 20, 24, 32, 40, 48, 64, 96, 256]
SVG_NS = "{http://www.w3.org/2000/svg}"


def read_png(data: bytes) -> tuple[int, int, bytes]:
    """(width, height, RGBA rows) of an 8-bit RGBA, non-interlaced PNG using filter 0."""
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    pos, idat, ihdr = 8, b"", None
    while pos < len(data):
        length, tag = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if tag == b"IHDR":
            ihdr = struct.unpack(">IIBBBBB", body)
        elif tag == b"IDAT":
            idat += body
        pos += 12 + length
    width, height, depth, colour, _, _, interlace = ihdr
    assert (depth, colour, interlace) == (8, 6, 0), "expected RGBA8, non-interlaced"
    raw = zlib.decompress(idat)
    stride = width * 4
    rows = []
    for y in range(height):
        line = raw[y * (stride + 1):(y + 1) * (stride + 1)]
        assert line[0] == 0, "only filter type 0 is written by make_icon"
        rows.append(line[1:])
    return width, height, b"".join(rows)


def ico_entries(data: bytes) -> dict[int, bytes]:
    reserved, kind, count = struct.unpack("<HHH", data[:6])
    assert (reserved, kind) == (0, 1), "not an icon file"
    out = {}
    for i in range(count):
        w, h, _, _, planes, bpp, size, offset = struct.unpack("<BBBBHHII", data[6 + 16 * i:22 + 16 * i])
        side = w or 256
        assert (w, planes, bpp) == (h, 1, 32), f"entry {i}: {w}x{h} planes={planes} bpp={bpp}"
        assert offset + size <= len(data), f"entry {i} runs past the end of the file"
        out[side] = data[offset:offset + size]
    return out


def dib_pixel(blob: bytes, side: int, x: int, y: int) -> tuple[int, int, int, int]:
    """RGBA of (x, y) from a top-left origin, in a bottom-up 32-bit icon DIB."""
    row = side - 1 - y
    b, g, r, a = blob[40 + (row * side + x) * 4:44 + (row * side + x) * 4]
    return r, g, b, a


class MasterSvgTest(unittest.TestCase):
    def setUp(self):
        self.text = MASTER.read_text(encoding="utf-8")
        self.root = ET.fromstring(self.text)

    def test_site_copy_is_identical(self):
        self.assertEqual(SITE_SVG.read_bytes(), MASTER.read_bytes(),
                         "site/assets/favicon.svg is stale: run _tools/make_icon.py")

    def test_square_viewbox(self):
        self.assertEqual(self.root.tag, SVG_NS + "svg")
        self.assertEqual(self.root.get("viewBox"), "0 0 256 256")

    def test_self_contained(self):
        # Favicons and <img> render SVG as an isolated image: scripts, external files and
        # foreignObject either do nothing or break it, so none may creep in.
        for el in self.root.iter():
            tag = el.tag.replace(SVG_NS, "")
            self.assertNotIn(tag, ("script", "foreignObject", "image", "use", "style"), tag)
            for name in el.attrib:
                self.assertFalse(name.lower().startswith("on"), f"event handler {name} on <{tag}>")
                self.assertFalse(name.endswith("href"), f"reference {name} on <{tag}>")
        defined = {el.get("id") for el in self.root.iter() if el.get("id")}
        for ref in re.findall(r"url\(#([^)]+)\)", self.text):
            self.assertIn(ref, defined, f"url(#{ref}) points at nothing")


def _points(text: str) -> list[tuple[float, float]]:
    nums = [float(n) for n in re.findall(r"-?\d+(?:\.\d+)?", text)]
    return list(zip(nums[0::2], nums[1::2], strict=True))


class NoteArrowShapeTest(unittest.TestCase):
    """The note arrow is the game's solid wedge. The app's slice-note arrow is the reference
    outline; the icon and the website's opening cut must draw that same shape (both once
    drew a hollow '>' chevron instead)."""

    def setUp(self):
        app = (PROJECT_ROOT / "frontend" / "app.js").read_text(encoding="utf-8")
        m = re.search(r'SLICE_NOTE_ARROW =\s*`<polygon points="([^"]+)"', app)
        self.assertIsNotNone(m, "SLICE_NOTE_ARROW not found in frontend/app.js")
        self.reference = _points(m.group(1))       # 500-unit viewBox, note body 450 wide

    def test_icon_arrow_is_the_reference_scaled_with_the_body(self):
        root = ET.fromstring(MASTER.read_text(encoding="utf-8"))
        bodies = {float(el.get("width")) for el in root.iter(SVG_NS + "rect") if el.get("fill") == "url(#sl-red)"}
        self.assertEqual(len(bodies), 1)
        k = bodies.pop() / 450
        want = [(128 + (x - 250) * k, 128 + (y - 250) * k) for x, y in self.reference]
        arrows = [el for el in root.iter(SVG_NS + "polygon")]
        self.assertEqual(len(arrows), 2, "one arrow per half")
        for el in arrows:
            self.assertNotEqual(el.get("fill", "none"), "none", "the arrow is solid, not an outline")
            got = _points(el.get("points"))
            self.assertEqual(len(got), len(want))
            for (gx, gy), (wx, wy) in zip(got, want, strict=True):
                self.assertAlmostEqual(gx, wx, delta=0.1)
                self.assertAlmostEqual(gy, wy, delta=0.1)

    def test_intro_arrow_is_the_reference(self):
        intro = (PROJECT_ROOT / "site" / "assets" / "intro.js").read_text(encoding="utf-8")
        m = re.search(r"var ARROW_OUTLINE = (\[\[.*?\]\]);", intro)
        self.assertIsNotNone(m, "ARROW_OUTLINE not found in site/assets/intro.js")
        self.assertEqual(_points(m.group(1)), self.reference)


class IcoTest(unittest.TestCase):
    def setUp(self):
        self.entries = ico_entries(ICO.read_bytes())

    def test_sizes(self):
        self.assertEqual(sorted(self.entries), ICO_SIZES)

    def test_small_entries_are_dibs(self):
        for side, blob in self.entries.items():
            if side == 256:
                continue
            size, w, h, planes, bpp, compression = struct.unpack("<IiiHHI", blob[:20])
            self.assertEqual((size, w, h, planes, bpp, compression), (40, side, side * 2, 1, 32, 0), side)
            mask_stride = ((side + 31) // 32) * 4
            self.assertEqual(len(blob), 40 + side * side * 4 + mask_stride * side, side)

    def test_large_entry_is_png(self):
        width, height, _ = read_png(self.entries[256])
        self.assertEqual((width, height), (256, 256))

    def test_pixels_are_the_icon(self):
        # Transparent corner, red left half, blue right half: catches BGRA/RGBA swaps
        # and upside-down rows, which a structural check alone would pass.
        blob = self.entries[48]
        self.assertEqual(dib_pixel(blob, 48, 0, 0)[3], 0)
        r, g, b, a = dib_pixel(blob, 48, 12, 32)
        self.assertTrue(a == 255 and r > 150 and b < 120, (r, g, b, a))
        r, g, b, a = dib_pixel(blob, 48, 36, 36)
        self.assertTrue(a == 255 and b > 150 and r < 120, (r, g, b, a))


class SiteRasterTest(unittest.TestCase):
    def test_favicon_png(self):
        width, height, px = read_png(SITE_PNG32.read_bytes())
        self.assertEqual((width, height), (32, 32))
        self.assertEqual(px[3], 0, "corner should be transparent")

    def test_touch_icon_is_opaque(self):
        # iOS fills transparency with black, so the icon carries the page colour itself
        width, height, px = read_png(SITE_TOUCH.read_bytes())
        self.assertEqual((width, height), (180, 180))
        self.assertTrue(all(a == 255 for a in px[3::4]))


